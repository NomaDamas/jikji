use jikji_core::storage::{cloud_drive_path_blocked, load_artifact, open_database, root_id};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

const AGENT_RULES_BEGIN: &str = "<!-- BEGIN JIKJI ROUTING (auto-generated by `jikji prepare`; do not edit inside this block) -->";
const AGENT_RULES_END: &str = "<!-- END JIKJI ROUTING -->";
const AGENT_RULE_FILES: &[&str] = &["AGENTS.md", "CLAUDE.md", ".cursorrules"];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum IndexStatus {
    Missing,
    Ready,
    StaleUsingPreviousIndex,
    ChangedUsingPreviousIndex,
}

impl IndexStatus {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Missing => "missing",
            Self::Ready => "ready",
            Self::StaleUsingPreviousIndex => "stale_using_previous_index",
            Self::ChangedUsingPreviousIndex => "changed_using_previous_index",
        }
    }
}

/// Whether the freshness check may walk the folder tree to see if files changed since indexing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TreeCheck {
    /// Walk the tree, within a time budget.
    Full,
    /// Do not touch the file system (the searched index belongs to a larger root).
    Skip,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SearchIndexStatus {
    pub status: IndexStatus,
    pub should_prepare: bool,
    /// False when the tree was not compared with the index (skipped, cloud mount, or the folder
    /// is too large to walk within the time budget): the index may lag behind the files.
    pub freshness_checked: bool,
}

/// Longest the tree walk of one search may take; larger folders report `freshness_checked: false`.
const FRESHNESS_BUDGET_MS: u64 = 2_000;

fn freshness_budget() -> Duration {
    let millis = std::env::var("JIKJI_FRESHNESS_BUDGET_MS")
        .ok()
        .and_then(|value| value.parse::<u64>().ok())
        .unwrap_or(FRESHNESS_BUDGET_MS);
    Duration::from_millis(millis)
}

pub fn search_index_status(root: &Path, stale_after_seconds: i64) -> SearchIndexStatus {
    search_index_status_with(root, stale_after_seconds, TreeCheck::Full)
}

pub fn search_index_status_with(
    root: &Path,
    stale_after_seconds: i64,
    tree: TreeCheck,
) -> SearchIndexStatus {
    let Some(manifest) = load_artifact(root, "manifest").ok().flatten() else {
        if has_search_docs(root) {
            return SearchIndexStatus {
                status: IndexStatus::Ready,
                should_prepare: false,
                freshness_checked: false,
            };
        }
        return SearchIndexStatus {
            status: IndexStatus::Missing,
            should_prepare: true,
            freshness_checked: false,
        };
    };
    let tree_state = if tree == TreeCheck::Full {
        tree_changed(root, &manifest)
    } else {
        None
    };
    if tree_state == Some(true) {
        return SearchIndexStatus {
            status: IndexStatus::ChangedUsingPreviousIndex,
            should_prepare: false,
            freshness_checked: true,
        };
    }
    let freshness_checked = tree_state.is_some();
    if stale_after_seconds >= 0 {
        let age = manifest
            .get("generated_at")
            .and_then(Value::as_u64)
            .map(|at| now_seconds().saturating_sub(at))
            .unwrap_or(u64::MAX);
        if age >= stale_after_seconds as u64 {
            return SearchIndexStatus {
                status: IndexStatus::StaleUsingPreviousIndex,
                should_prepare: false,
                freshness_checked,
            };
        }
    }
    SearchIndexStatus {
        status: IndexStatus::Ready,
        should_prepare: false,
        freshness_checked,
    }
}

fn has_search_docs(root: &Path) -> bool {
    let Ok(connection) = open_database() else {
        return false;
    };
    let Ok(Some(id)) = root_id(&connection, root) else {
        return false;
    };
    connection
        .query_row(
            "SELECT COUNT(*) FROM search_docs WHERE root_id=?1",
            [id],
            |row| row.get::<_, i64>(0),
        )
        .ok()
        .is_some_and(|count| count > 0)
}

/// `Some(changed)` after comparing the tree with the manifest; `None` when it could not be compared
/// (no stored signature, a cloud mount that must not be walked, or the time budget ran out).
fn tree_changed(root: &Path, manifest: &Value) -> Option<bool> {
    let stored = manifest
        .get("source_tree_signature")
        .and_then(|value| value.get("digest"))
        .and_then(Value::as_str)?;
    if cloud_drive_path_blocked(root) {
        return None;
    }
    // The index remembers how many files the tree had. A tree that size cannot be walked within the
    // budget, so walking it only burns the whole budget on every search and ends in "not checked"
    // anyway: say so at once.
    let stored_files = manifest
        .get("source_tree_signature")
        .and_then(|value| value.get("files"))
        .and_then(Value::as_u64)
        .unwrap_or(0);
    if stored_files > max_files_for_budget(freshness_budget()) {
        return None;
    }
    let current = compute_source_tree_digest(root, Instant::now() + freshness_budget())?;
    Some(current != stored)
}

/// Files the freshness walk can be expected to cover within `budget`. Measured at hundreds of
/// thousands of files per second warm; the margin covers a cold disk and the per-file metadata read
/// of the digest pass that follows the walk.
fn max_files_for_budget(budget: Duration) -> u64 {
    const FILES_PER_SECOND: u64 = 20_000;
    FILES_PER_SECOND.saturating_mul(budget.as_millis().min(u128::from(u64::MAX)) as u64) / 1000
}

fn compute_source_tree_digest(root: &Path, deadline: Instant) -> Option<String> {
    let mut files = Vec::new();
    if !collect_files(root, root, &mut files, deadline) {
        return None;
    }
    files.sort();
    let mut hasher = Sha256::new();
    for path in files {
        if Instant::now() >= deadline {
            return None;
        }
        let Ok(metadata) = fs::metadata(&path) else {
            continue;
        };
        let rel = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace(std::path::MAIN_SEPARATOR, "/");
        hasher.update(rel.as_bytes());
        hasher.update(b"\0");
        hasher.update(metadata.len().to_string().as_bytes());
        hasher.update(b"\0");
        hasher.update(mtime_ns(&metadata).to_string().as_bytes());
        hasher.update(b"\n");
    }
    Some(format!("{:x}", hasher.finalize()))
}

/// Collects the files below `current`; false when `deadline` passed before the walk finished.
fn collect_files(root: &Path, current: &Path, files: &mut Vec<PathBuf>, deadline: Instant) -> bool {
    let Ok(entries) = fs::read_dir(current) else {
        return true;
    };
    for entry in entries.flatten() {
        if Instant::now() >= deadline {
            return false;
        }
        let name = entry.file_name().to_string_lossy().into_owned();
        if name == ".jikji" || name.starts_with('.') || is_sensitive(&name) {
            continue;
        }
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        let path = entry.path();
        if file_type.is_dir() {
            if !collect_files(root, &path, files, deadline) {
                return false;
            }
        } else if file_type.is_file()
            && path.starts_with(root)
            && !is_pure_generated_agent_rule(&path, &name)
        {
            files.push(path);
        }
    }
    true
}

fn is_pure_generated_agent_rule(path: &Path, name: &str) -> bool {
    if !AGENT_RULE_FILES.contains(&name) {
        return false;
    }
    let Ok(text) = fs::read_to_string(path) else {
        return false;
    };
    let trimmed = text.trim();
    trimmed.starts_with(AGENT_RULES_BEGIN) && trimmed.ends_with(AGENT_RULES_END)
}

fn is_sensitive(name: &str) -> bool {
    matches!(
        name,
        ".git" | ".hg" | ".svn" | "node_modules" | "__pycache__" | ".venv" | "venv"
    ) || name.ends_with(".pem")
        || name.ends_with(".key")
}

fn now_seconds() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |duration| duration.as_secs())
}

fn mtime_ns(metadata: &fs::Metadata) -> u128 {
    metadata
        .modified()
        .ok()
        .and_then(|modified| modified.duration_since(UNIX_EPOCH).ok())
        .map_or(0, |duration| duration.as_nanos())
}

#[cfg(test)]
mod tests {
    use std::time::Duration;

    use serde_json::json;

    use super::{max_files_for_budget, tree_changed};

    #[test]
    fn the_walk_budget_covers_a_known_number_of_files() {
        assert_eq!(max_files_for_budget(Duration::from_millis(0)), 0);
        assert_eq!(max_files_for_budget(Duration::from_secs(1)), 20_000);
        assert_eq!(max_files_for_budget(Duration::from_millis(2_000)), 40_000);
    }

    #[test]
    fn a_tree_bigger_than_the_budget_covers_is_not_walked_and_reports_not_compared() {
        // The root does not exist: a walk would find nothing and a digest would differ. Not
        // comparing at all (`None`) is only possible when the stored file count rules the walk out.
        let huge = json!({"source_tree_signature": {"digest": "x", "files": 900_000}});
        assert_eq!(
            tree_changed(std::path::Path::new("/no/such/root"), &huge),
            None
        );
        // A small tree is compared: the digest of an empty walk differs from the stored one.
        let small = json!({"source_tree_signature": {"digest": "x", "files": 3}});
        assert_eq!(
            tree_changed(std::path::Path::new("/no/such/root"), &small),
            Some(true)
        );
    }
}
